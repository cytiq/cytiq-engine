# Reference values of flowWorkspace::flowjo_biexp at non-default parameters
# (negative decades, another range and width), for the `--biexponential-*`
# flags of `cytiq transform`. Writes only
# data/fixtures/transform/flowjo_biexp_params.rs; existing fixtures are
# untouched.
#
# Usage: R_LIBS_USER=parity/.env/Rlib Rscript parity/gen/flowjo_biexp_params.R
suppressPackageStartupMessages(library(flowWorkspace))
num <- function(v) sprintf("%.17g", v)
arr <- function(name, v) sprintf("pub const %s: [f64; %d] = [%s];\n", name, length(v),
                                 paste(sub("^(-?[0-9]+)$", "\\1.0", num(v)), collapse = ", "))
x <- c(-50000, -10000, -1000, -100, -10, 0, 10, 100, 1000, 10000, 1e5, 262144)
cases <- list(
  NEG = list(channelRange = 1024, maxValue = 100000, pos = 4, neg = 0.5, widthBasis = -50),
  WIDE = list(channelRange = 256, maxValue = 262144, pos = 4.5, neg = 1, widthBasis = -1000)
)
out <- file("data/fixtures/transform/flowjo_biexp_params.rs", "w")
cat("// Generated by parity/gen/flowjo_biexp_params.R with", R.version.string, "\n", file = out)
cat("// flowWorkspace", as.character(packageVersion("flowWorkspace")), "\n", file = out)
cat(arr("BIEXP_PARAMS_INPUT", x), file = out)
for (name in names(cases)) {
  p <- cases[[name]]
  forward <- do.call(flowjo_biexp, p)
  cat(sprintf("// flowjo_biexp(channelRange = %s, maxValue = %s, pos = %s, neg = %s, widthBasis = %s)\n",
              p$channelRange, p$maxValue, p$pos, p$neg, p$widthBasis), file = out)
  cat(arr(paste0("BIEXP_", name), forward(x)), file = out)
}
close(out)
