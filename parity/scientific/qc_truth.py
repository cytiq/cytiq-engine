REFERENCE = ROOT / "data/fixtures/scientific/qc-truth.json"
SAMPLE = "GOLDEN"
FLUORESCENCE = ",".join(pipeline.FLUOR[:5])
# The channels compensate's `margin_pass` assesses: the spillover detectors
# and every scatter channel (`cytiq_fcs::margin_channels`).
MARGIN_CHANNELS = [*pipeline.FLUOR, "FSC-A", "FSC-H", "FSC-W", "SSC-A"]
TRUTH_CLASS = {"debris": "synthetic", "doublet": "synthetic", "dead": "synthetic",
               "time_anomaly": "synthetic", "saturated": "definitional"}
METRICS = ("sensitivity", "specificity", "precision")

REAL_DATA = {
    "status": "not_assessed",
    "reason": "no real acquisition with independent artifact truth (an orthogonal assay or "
              "adjudicated expert labels with measured agreement) is pinned; published population "
              "labels identify populations, not artifacts",
    "domains": {domain: "not_assessed" for domain in DOMAINS if domain != "all"},
    "required": "parity/scientific/README.md#required-real-data-for-artifact-truth",
}

# Pinned by `test_qc_truth.py`: changing the protocol is a reviewed change.
POLICY_PROTOCOL = """\
QC acceptance-policy derivation protocol, version 1.
1. Truth: only classes whose declared truth class is `independent` or
   `expert_reference` may derive a bound. Synthetic, definitional and
   exploratory truth never derive one.
2. Data: at least two independent real derivation datasets and at least one
   real held-out evaluation dataset. No acquisition SHA-256 may appear in
   both (`disjoint_acquisitions`).
3. Freeze: the population, its rare designation, the metric (clean retention
   or frequency error against clean events) and the bound rule are fixed and
   committed with the derivation data's hashes before any held-out
   acquisition is evaluated.
4. Bound: the default rule is the lowest 95% Wilson lower limit of the
   population's clean retention over the derivation datasets; it must hold
   on every held-out dataset, or no bound is proposed.
5. Adoption: a bound that holds only opens a reviewed `QcPolicy` change for
   the panel. Nothing is adopted automatically, and descriptive retention
   never changes a status, an exit code or a release decision.
"""
ELIGIBLE_TRUTH = ("independent", "expert_reference")
# Real datasets registered under POLICY_PROTOCOL: none yet.
POLICY_DATASETS: list[dict] = []


def protocol_sha256():
    return hashlib.sha256(POLICY_PROTOCOL.encode()).hexdigest()


def disjoint_acquisitions(derivation, evaluation):
    shared = sorted(set(derivation) & set(evaluation))
    if shared:
        raise ValueError(f"derivation and held-out evaluation share acquisitions: {shared}")


def policy_design(derivation, evaluation):
    """Raise unless these datasets may derive and test a bound under
    POLICY_PROTOCOL. A dataset is `{name, real, truth_classes, acquisitions}`."""
    if len(derivation) < 2:
        raise ValueError("a bound needs at least two independent real derivation datasets")
    if not evaluation:
        raise ValueError("a bound needs at least one real held-out evaluation dataset")
    for dataset in [*derivation, *evaluation]:
        if not dataset["real"]:
            raise ValueError(f"{dataset['name']}: synthetic data never derives a bound")
        ineligible = {name: kind for name, kind in dataset["truth_classes"].items()
                      if kind not in ELIGIBLE_TRUTH}
        if ineligible:
            raise ValueError(f"{dataset['name']}: truth classes {ineligible} cannot derive a bound")
    disjoint_acquisitions([a for d in derivation for a in d["acquisitions"]],
                          [a for d in evaluation for a in d["acquisitions"]])


def policy_status():
    derivation = [d for d in POLICY_DATASETS if d.get("role") == "derivation"]
    evaluation = [d for d in POLICY_DATASETS if d.get("role") == "evaluation"]
    try:
        policy_design(derivation, evaluation)
    except ValueError as error:
        return {"status": "not_assessed", "reason": f"no independently labelled real acquisitions: {error}"}
    return {"status": "design_eligible", "datasets": [d["name"] for d in POLICY_DATASETS]}


# ---- scenario data and inputs

def scenario_data(name, seed):
    spec = SCENARIOS[name]
    profile = {**pipeline.PROFILES["ci"], **spec["profile"]}
    data, truth = pipeline.generate(profile, np.random.default_rng(seed))
    if "attenuate" in spec:
        settings = spec["attenuate"]
        matrix = pd.DataFrame(pipeline.SPILL, index=pipeline.FLUOR, columns=pipeline.FLUOR)
        rows = truth.population.isin(settings["populations"]).to_numpy()
        data = attenuate(data, pipeline.CHANNELS, matrix, rows, settings["factor"], settings["dye"])
    return data, truth


def definitional_saturation(path):
    """Events at or above `$PnR - 1` on a margin channel of the written file."""
    values, names = read_fcs(path)
    flow = flowio.FlowData(str(path), ignore_offset_discrepancy=True)
    limits = np.array([float(flow.text[f"p{names.index(c) + 1}r"]) - 1 for c in MARGIN_CHANNELS])
    return (values[:, [names.index(c) for c in MARGIN_CHANNELS]] >= limits).any(axis=1)


def generated(method):
    return {"evidence": "generative", "selection": "all_events", "method": method, "channels": []}


def descriptor(scenario, seed):
    return {
        "annotation": {
            "producer": "parity/gen/pipeline.py",
            "protocol": f"parity/scientific/qc_scenarios.py scenario `{scenario}`, seed {seed}",
            "reference": "parity/scientific/README.md#qc-artifact-truth-benchmark",
        },
        "classes": {
            "debris": generated("generated debris: low FSC/SSC and no cell signal"),
            "doublet": generated("two generated cells summed into one pulse"),
            "dead": generated("generated dying cells: shrunken scatter, bright viability dye"),
            "time_anomaly": generated("every event of the generated unstable interval: a clog, then a gain drift"),
            "saturated": {"evidence": "definitional", "selection": "all_events",
                          "method": "a raw value at or above $PnR - 1 on a spillover detector or scatter channel of the written FCS",
                          "channels": MARGIN_CHANNELS},
        },
    }


def write_truth(path, classes, acquisition, scenario, seed):
    events = len(classes["debris"])
    fields = [pa.field("source_event_id", pa.uint64(), nullable=False)]
    arrays = [pa.array(np.arange(events, dtype=np.uint64))]
    for name in TRUTH_CLASSES:
        fields.append(pa.field(name, pa.bool_()))
        arrays.append(pa.array(classes[name].astype(bool)))
    metadata = {"cytiq.qc_truth.schema_version": "1", "cytiq.acquisition_sha256": acquisition,
                "cytiq.qc_truth.descriptor": json.dumps(descriptor(scenario, seed))}
    table = pa.Table.from_arrays(arrays, schema=pa.schema(fields, metadata=metadata))
    pq.write_table(table, path, compression="none")


def write_membership(path, populations, acquisition):
    """A `cytiq.mask.v2` membership of the true populations over every raw event."""
    events = len(populations[0][1])
    ids = pa.array(np.arange(events, dtype=np.uint64))
    fields = [pa.field("event_id", pa.uint64(), nullable=False),
              pa.field("source_event_id", pa.uint64(), nullable=False)]
    arrays = [ids, ids]
    for name, members in populations:
        fields.append(pa.field(name, pa.bool_()))
        arrays.append(pa.array(members))
    fields.append(pa.field("keep", pa.bool_(), nullable=False))
    arrays.append(pa.array(np.ones(events, dtype=bool)))
    metadata = {"cytiq.mask.schema_version": "2", "cytiq.acquisition_sha256": acquisition,
                "cytiq.event_id_base": "0"}
    pq.write_table(pa.Table.from_arrays(arrays, schema=pa.schema(fields, metadata=metadata)),
                   path, compression="none")


# ---- the chain, lineage and the oracle

def run_chain(binary, case):
    sample = case / "sample.fcs"
    steps = [
        ["compensate", "--input", sample, "--output", case / "s.comp.fcs"],
        ["transform", "--input", case / "s.comp.fcs", "--output", case / "s.t.fcs"],
        ["peacoqc", "--input", case / "s.t.fcs", "--output", case / "s.peacoqc.fcs", "--channels", FLUORESCENCE],
        ["clean", "--input", sample, "--output", case / "clean"],
        ["mask", "combine", "--mask", case / "s.comp.masks.parquet", "--mask", case / "s.peacoqc.masks.parquet",
         "--mask", case / "clean/masks.parquet", "--output", case / "analysis.parquet"],
    ]
    for index, args in enumerate(steps):
        invoke(binary, args, case / f"{index}.log")


def run_qc(binary, case):
    """`cytiq qc` with truth and populations. Exit 3 (failed policy checks) is
    a result, not an error: truth never changes it."""
    args = [binary, "qc", "--manifest", case / "run.yaml", "--sample", SAMPLE,
            "--mask", case / "analysis.parquet", "--output", case / "qc.json",
            "--artifact-truth", case / "truth.parquet", "--populations", case / "populations.parquet"]
    with (case / "qc.log").open("w") as log:
        result = subprocess.run([str(a) for a in args], stdout=log, stderr=log,
                                env={**os.environ, "RAYON_NUM_THREADS": "4"})
    if result.returncode not in (0, 3):
        raise RuntimeError(f"cytiq qc exited {result.returncode}: see {case / 'qc.log'}")
    return result.returncode, json.loads((case / "qc.json").read_text())


def read_mask(path, acquisition, events):
    metadata = pq.read_metadata(path).metadata
    if metadata[b"cytiq.acquisition_sha256"].decode() != acquisition:
        raise ValueError(f"{path}: mask of another acquisition")
    table = pq.read_table(path)
    ids = table.column("source_event_id").to_numpy()
    if len(ids) != events or not np.array_equal(np.sort(ids), np.arange(events)):
        raise ValueError(f"{path}: incomplete source lineage")
    keep = table.column("keep").to_numpy(zero_copy_only=False).astype(bool)
    filters = [(name, table.column(name).to_pylist()) for name in table.column_names
               if name not in ("event_id", "source_event_id", "keep")]
    return ids, keep, filters


def raw_order(ids, values):
    ordered = np.empty(len(ids), dtype=bool)
    ordered[ids] = values
    return ordered


def first_difference(rust, oracle, path="$"):
    if isinstance(rust, dict) and isinstance(oracle, dict):
        for key in sorted(set(rust) | set(oracle)):
            found = first_difference(rust.get(key, "<absent>"), oracle.get(key, "<absent>"), f"{path}.{key}")
            if found:
                return found
        return None
    if isinstance(rust, list) and isinstance(oracle, list):
        if len(rust) != len(oracle):
            return f"{path}: {len(rust)} != {len(oracle)} entries"
        for index, (a, b) in enumerate(zip(rust, oracle)):
            found = first_difference(a, b, f"{path}[{index}]")
            if found:
                return found
        return None
    if type(rust) is not type(oracle) or rust != oracle:
        return f"{path}: Rust {rust!r} != oracle {oracle!r}"
    return None


def agree(what, rust, oracle):
    found = first_difference(rust, oracle)
    if found:
        raise ValueError(f"{what}: Rust and the NumPy oracle disagree at {found}")


def measure(binary, scenario, seed, case, with_qc=True):
    """Generate, run the chain and recompute every metric independently."""
    case.mkdir(parents=True)
    data, truth = scenario_data(scenario, seed)
    pipeline.write(case, data, truth)
    events = len(truth)
    acquisition = sha256(case / "sample.fcs")
    classes = {"debris": truth.debris.to_numpy(), "doublet": truth.doublet.to_numpy(),
               "dead": truth.dead.to_numpy(), "time_anomaly": truth.unstable.to_numpy(),
               "saturated": definitional_saturation(case / "sample.fcs").astype(int)}
    write_truth(case / "truth.parquet", classes, acquisition, scenario, seed)
    names = sorted(set(truth.population) - {"none"})
    populations = [(name, (truth.population == name).to_numpy()) for name in names]
    write_membership(case / "populations.parquet", populations, acquisition)
    run_chain(binary, case)
    for stage in ("s.comp.masks.parquet", "s.peacoqc.masks.parquet", "clean/masks.parquet"):
        read_mask(case / stage, acquisition, events)
    ids, keep, filters = read_mask(case / "analysis.parquet", acquisition, events)
    codes = {name: values.astype(np.int8) for name, values in classes.items()}
    removal = artifact_removal_oracle(ids, keep, filters, codes, events)
    stages = [("combined", raw_order(ids, keep))]
    stages += [(name, raw_order(ids, [value is not False for value in values])) for name, values in filters]
    retention = membership_retention_oracle(populations, stages, event_states(codes))
    result = {"scenario": scenario, "seed": seed, "acquisition": acquisition, "events": events,
              "generator_saturated_agrees": bool(np.array_equal(classes["saturated"], truth.margin.to_numpy())),
              "artifact_removal": removal, "population_retention": retention}
    if with_qc:
        code, report = run_qc(binary, case)
        section = report["artifact_removal"]
        if section["status"] != "assessed":
            raise ValueError(f"{scenario}/{seed}: artifact removal not assessed: {section.get('reason')}")
        agree(f"{scenario}/{seed} artifact_removal",
              {key: section[key] for key in ("events", "combined", "filters")}, removal)
        populations_report = report["population_retention"]
        agree(f"{scenario}/{seed} population_retention",
              [populations_report["combined"], *populations_report["filters"]], retention)
        result["qc"] = {"exit_code": code, "status": report["status"],
                        "truth_classes": {c["class"]: c["truth_class"] for c in section["truth"]["classes"]}}
        if result["qc"]["truth_classes"] != TRUTH_CLASS:
            raise ValueError(f"{scenario}/{seed}: declared truth classes changed")
    return result


# ---- frozen reference and summaries

def counts(case):
    """Integer counts that pin a case: every ratio derives from them."""
    removal = case["artifact_removal"]
    events = {key: value for key, value in removal["events"].items() if key != "clean_of"}
    filters = {}
    for entry in removal["filters"]:
        target = entry.get("target", {})
        filters[entry["column"]] = {"events": entry["events"], "removed_by_class": entry["removed_by_class"],
                                    "target": target.get("outcomes", target.get("status"))}
    populations = {row["population"]: {key: row[key] for key in
                   ("original", "retained", "good_original", "good_retained", "technical_removed", "undetermined_removed")}
                   for row in case["population_retention"][0]["populations"]}
    return {"acquisition": case["acquisition"], "events": events,
            "combined": {"kept": removal["combined"]["kept"], "events": removal["combined"]["events"],
                         "classes": removal["combined"]["classes"]},
            "filters": filters, "populations": populations}


def compare_reference(cases, reference):
    compared = 0
    for scenario, seeds in reference["cases"].items():
        for seed, expected in seeds.items():
            measured = cases.get(scenario, {}).get(seed)
            if measured is None:
                continue
            found = first_difference(counts(measured), expected)
            if found:
                raise ValueError(f"{scenario}/{seed}: differs from the frozen reference ({found}); scientific review required")
            compared += 1
    return compared


def stats(values):
    values = [v for v in values if v is not None]
    if not values:
        return {"n": 0}
    return {"n": len(values), "min": min(values), "median": statistics.median(values), "max": max(values)}


def summarize(cases):
    """Per scenario, across seeds: column metrics, combined removal and
    population retention, with Wilson intervals for rare populations."""
    summary = {}
    for scenario, seeds in cases.items():
        runs = list(seeds.values())
        filters = {}
        for column in DOMAIN_COLUMNS.values():
            entries = [next(f for f in run["artifact_removal"]["filters"] if f["column"] == column) for run in runs]
            target = [entry.get("target", {}) for entry in entries]
            filters[column] = {"class": target[0].get("class"),
                               "status": sorted({t.get("status") for t in target}),
                               "clean_loss": stats([e["clean_loss"]["value"] for e in entries])}
            for metric in METRICS:
                filters[column][metric] = stats([t[metric]["value"] if metric in t else None for t in target])
        combined = [run["artifact_removal"]["combined"] for run in runs]
        populations = {}
        names = sorted({row["population"] for run in runs for row in run["population_retention"][0]["populations"]})
        for name in names:
            rows = [next((row for row in run["population_retention"][0]["populations"] if row["population"] == name),
                         None) for run in runs]
            runs_with, rows = [run for run, row in zip(runs, rows) if row], [row for row in rows if row]
            populations[name] = {key: stats([r[key] for r in rows]) for key in
                                 ("good_retention", "frequency_error_vs_clean", "relative_frequency_error_vs_clean")}
            if name in RARE:
                populations[name]["seeds"] = [
                    {"seed": run["seed"], "good_retained": r["good_retained"], "good_original": r["good_original"],
                     "wilson_95": wilson_interval(r["good_retained"], r["good_original"]) if r["good_original"] else None}
                    for run, r in zip(runs_with, rows)]
                populations[name]["wilson_basis"] = "conditional on each acquisition's fitted gates and filters; seeds vary the data"
        summary[scenario] = {
            "domain": SCENARIOS[scenario]["domain"], "seeds": len(runs),
            "qc_exit_codes": sorted({run["qc"]["exit_code"] for run in runs if "qc" in run}),
            "filters": filters,
            "combined": {key: stats([c[key]["value"] for c in combined]) for key in
                         ("artifact_recall", "clean_retention", "removed_artifact_share")}
            | {"total_retention": stats([c["total_retention"] for c in combined])},
            "populations": populations,
        }
    return summary


# ---- commands

def synthetic(args):
    output = args.output
    output.mkdir(parents=True, exist_ok=False)
    started = time.time()
    seeds = SEEDS[:args.seeds]
    scenarios = args.scenarios or list(SCENARIOS)
    report = {"schema_version": 1, "benchmark": "qc_artifact_truth", "status": "failed",
              "validation": "synthetic_only",
              "basis": "synthetic algorithm evidence: generated artifacts and definitional saturation; not biological validation and never a QC decision",
              "binary_sha256": sha256(args.binary),
              "generator_sha256": sha256(ROOT / "parity/gen/pipeline.py"),
              "scenarios_sha256": sha256(Path(__file__).with_name("qc_scenarios.py")),
              "oracle_sha256": sha256(Path(__file__).with_name("metrics.py")),
              "runner_sha256": sha256(Path(__file__)),
              "seeds": list(seeds), "scenarios": scenarios, "truth_classes": TRUTH_CLASS,
              "real_data": REAL_DATA, "policy_protocol_sha256": protocol_sha256(),
              "policy_derivation": policy_status(), "cases": {}}
    try:
        for scenario in scenarios:
            for seed in seeds:
                case = measure(args.binary, scenario, seed, output / scenario / str(seed))
                report["cases"].setdefault(scenario, {})[str(seed)] = case
                if scenario == "baseline" and seed == pipeline.SEED:
                    fixture = ROOT / "data/fixtures/pipeline/sample.fcs"
                    if case["acquisition"] != sha256(fixture):
                        raise ValueError("baseline seed no longer reproduces data/fixtures/pipeline/sample.fcs")
        if args.no_reference:
            report["reference"] = {"status": "not_compared", "reason": "--no-reference"}
        else:
            reference = json.loads(args.reference.read_text())
            report["reference"] = {"status": "matched", "path": str(args.reference),
                                   "cases": compare_reference(report["cases"], reference),
                                   "baseline_commit": reference["baseline_commit"]}
        if args.baseline_bin is not None:
            for scenario, seeds_ in report["cases"].items():
                for seed, case in seeds_.items():
                    baseline = measure(args.baseline_bin, scenario, int(seed),
                                       output / "baseline" / scenario / seed, with_qc=False)
                    found = first_difference(counts(baseline), counts(case))
                    if found:
                        raise ValueError(f"{scenario}/{seed}: filtering changed from the baseline binary ({found})")
            report["baseline"] = {"binary_sha256": sha256(args.baseline_bin), "identical_counts": True}
        report["summary"] = summarize(report["cases"])
        report["status"] = "completed"
    except Exception as error:
        report["error"] = f"{type(error).__name__}: {error}"
        raise
    finally:
        report["wall_seconds"] = time.time() - started
        (output / "report.json").write_text(json.dumps(report, indent=2, allow_nan=False) + "\n")


def number(value, digits=4):
    return "—" if value is None else f"{value:.{digits}f}"


def cell(stat):
    if not stat or stat.get("n", 0) == 0:
        return "not assessed"
    if stat["min"] == stat["max"]:
        return number(stat["median"])
    return f"{number(stat['median'])} [{number(stat['min'])}, {number(stat['max'])}]"


def table(args):
    report = json.loads(args.report.read_text())
    if report.get("status") != "completed":
        raise ValueError("the report did not complete")
    summary = report["summary"]
    lines = [f"# QC artifact-truth benchmark ({report['validation']})", "",
             f"Seeds per scenario: {len(report['seeds'])}. Cells: median [min, max] over seeds. "
             f"Truth classes: {', '.join(f'{k} {v}' for k, v in report['truth_classes'].items())}. "
             f"Real data: {report['real_data']['status']}. Policy derivation: {report['policy_derivation']['status']}.", ""]
    for domain, column in DOMAIN_COLUMNS.items():
        names = ["baseline", *[s for s, v in summary.items() if v["domain"] == domain]]
        lines += [f"## {domain}: `{column}`", "",
                  "| Scenario | Sensitivity | Specificity | Precision | Clean loss |", "|---|---|---|---|---|"]
        for name in names:
            if name not in summary:
                continue
            filt = summary[name]["filters"][column]
            if "assessed" not in filt["status"]:
                lines.append(f"| {name} | not assessed | not assessed | not assessed | not assessed |")
                continue
            lines.append(f"| {name} | {cell(filt['sensitivity'])} | {cell(filt['specificity'])} | "
                         f"{cell(filt['precision'])} | {cell(filt['clean_loss'])} |")
        lines.append("")
    lines += ["## Combined keep", "", "| Scenario | Artifact recall | Clean retention | Removed artifact share | Total retention | qc exit |",
              "|---|---|---|---|---|---|"]
    for name, entry in summary.items():
        c = entry["combined"]
        lines.append(f"| {name} | {cell(c['artifact_recall'])} | {cell(c['clean_retention'])} | "
                     f"{cell(c['removed_artifact_share'])} | {cell(c['total_retention'])} | {entry['qc_exit_codes']} |")
    lines += ["", "## Population clean retention (combined keep)", ""]
    populations = sorted({p for entry in summary.values() for p in entry["populations"]})
    lines += ["| Scenario | " + " | ".join(populations) + " |", "|---|" + "---|" * len(populations)]
    for name, entry in summary.items():
        lines.append(f"| {name} | " + " | ".join(cell(entry["populations"].get(p, {}).get("good_retention"))
                                               for p in populations) + " |")
    lines += ["", "## Frequency error against clean events (combined keep)", "",
              "| Scenario | " + " | ".join(populations) + " |", "|---|" + "---|" * len(populations)]
    for name, entry in summary.items():
        lines.append(f"| {name} | " + " | ".join(cell(entry["populations"].get(p, {}).get("relative_frequency_error_vs_clean"))
                                               for p in populations) + " |")
    lines += ["", "Real-data artifact removal for every domain: not assessed "
              f"({report['real_data']['reason']})."]
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "table.md").write_text("\n".join(lines) + "\n")


def freeze(args):
    """Explicit maintenance: pin the integer counts of the CI seeds."""
    report = json.loads(args.report.read_text())
    if report.get("status") != "completed" or report.get("baseline", {}).get("identical_counts") is not True:
        raise ValueError("freeze needs a completed report whose counts the baseline binary reproduced")
    cases = {scenario: {seed: counts(case) for seed, case in seeds.items() if int(seed) in CI_SEEDS}
             for scenario, seeds in report["cases"].items()}
    reference = {"schema_version": 1, "baseline_commit": args.baseline_commit,
                 "baseline_binary_sha256": report["baseline"]["binary_sha256"],
                 "generator_sha256": report["generator_sha256"], "scenarios_sha256": report["scenarios_sha256"],
                 "basis": "integer counts of clean-main filtering on generated scenarios; synthetic, not biological validation",
                 "cases": cases}
    args.output.write_text(reference_text(reference))


def reference_text(reference):
    """Metadata indented, then one compact, sorted line per case: small, and
    a diff names the scenario and seed that changed."""
    lines = ["{"]
    for key in sorted(k for k in reference if k != "cases"):
        lines.append(f"  {json.dumps(key)}: {json.dumps(reference[key])},")
    lines.append('  "cases": {')
    scenarios = sorted(reference["cases"])
    for i, scenario in enumerate(scenarios):
        lines.append(f"    {json.dumps(scenario)}: {{")
        seeds = sorted(reference["cases"][scenario])
        for j, seed in enumerate(seeds):
            case = json.dumps(reference["cases"][scenario][seed], sort_keys=True, separators=(",", ":"))
            lines.append(f"      {json.dumps(seed)}: {case}" + ("," if j < len(seeds) - 1 else ""))
        lines.append("    }" + ("," if i < len(scenarios) - 1 else ""))
    lines += ["  }", "}"]
    return "\n".join(lines) + "\n"


