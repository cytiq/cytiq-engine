#!/usr/bin/env python3
"""QC artifact-truth benchmark: removal of technical artifacts, measured
separately from the retention of biological populations.

Every scenario (`qc_scenarios.py`) is generated by `parity/gen/pipeline.py`,
which knows each event's debris, doublet, dead-cell and time-anomaly status
(`synthetic` truth); saturation is recomputed from the written raw values
(`definitional` truth). The real chain (compensate, transform, PeacoQC,
clean, mask combine) runs on each, `cytiq qc --artifact-truth --populations`
reports on it, and an independent NumPy port (`metrics.py`) must reproduce
every count and ratio exactly. Results are synthetic evidence of algorithm
behaviour only. No real acquisition with independent artifact truth is
pinned, so real-data removal accuracy and acceptance-policy derivation are
`not_assessed`; nothing here changes a QC policy or a release decision.

    qc_truth.py synthetic --binary BIN --output DIR [--seeds 3] [--baseline-bin BIN]
    qc_truth.py table --report DIR/report.json --output DIR
    qc_truth.py freeze --report DIR/report.json --baseline-commit SHA   # explicit maintenance
"""
